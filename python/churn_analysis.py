"""Customer churn & retention analysis.

Reads data/customers.csv (generated by data/generate_churn_data.py),
runs the full analysis, saves charts to images/, and writes a
results_summary.txt with every headline number (used for the README).

Sections: EDA -> feature engineering -> cohorts -> drivers -> LTV:CAC ->
MoM trend -> chi-square significance -> confidence intervals.
"""

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats

sns.set_theme(style="whitegrid")
TODAY = pd.Timestamp("2026-09-26")
ASSUMED_CAC = {"Startup": 6_000, "SMB": 18_000, "Mid-market": 60_000}  # ASSUMED, not measured

df = pd.read_csv("../data/customers.csv", parse_dates=["signup_date", "churn_date"])
N = len(df)
out = []

def log(line=""):
    print(line)
    out.append(line)

# ================================================================ 1. EDA ===
log("=== EDA ===")
overall = df["churned"].mean()
log(f"Customers: {N:,}")
log(f"Overall churn rate: {overall:.1%}")
log("\nCustomer mix (plan):")
log(df["plan"].value_counts(normalize=True).mul(100).round(1).to_string())
log("\nCustomer mix (segment):")
log(df["segment"].value_counts(normalize=True).mul(100).round(1).to_string())

# ============================================== 2. Feature engineering ===
# Derive analysis features from raw columns (classic BA feature engineering).
df["cohort"] = df["signup_date"].dt.to_period("M").astype(str)
df["active_months"] = np.where(
    df["churned"] == 1,
    np.clip(((df["churn_date"] - df["signup_date"]).dt.days // 30), 0, None),
    df["tenure_months"],
)
df["tickets_per_month"] = (df["support_tickets_last_90d"] / 3).round(2)
df["is_high_ticket"] = (df["support_tickets_last_90d"] >= 4).astype(int)
df["recency_bucket"] = pd.cut(
    df["days_since_last_login"],
    bins=[0, 7, 30, 91],
    labels=["active (0-7d)", "lapsing (8-30d)", "dormant (31d+)"],
)
df["revenue_tier"] = pd.qcut(df["monthly_revenue"], 3,
                             labels=["low", "mid", "high"])
log("\n=== Engineered features ===")
log("active_months, tickets_per_month, is_high_ticket, recency_bucket, revenue_tier")

# ================================================== 3. Cohort retention ===
cohorts = sorted(df["cohort"].unique())
max_k = 11
ret = pd.DataFrame(index=cohorts, columns=range(max_k + 1), dtype=float)
for c in cohorts:
    sub = df[df["cohort"] == c]
    observable = (TODAY.year - int(c[:4])) * 12 + (TODAY.month - int(c[5:7]))
    for k in range(max_k + 1):
        if k < observable:
            ret.loc[c, k] = (sub["active_months"] > k).mean()

fig, ax = plt.subplots(figsize=(11, 6))
sns.heatmap(ret, annot=True, fmt=".0%", cmap="YlGn", vmin=0, vmax=1,
            cbar_kws={"label": "retention"}, ax=ax, mask=ret.isna())
ax.set_title("Cohort retention: % of customers still active k months after signup")
ax.set_xlabel("Months since signup"); ax.set_ylabel("Signup cohort")
plt.tight_layout(); plt.savefig("../images/cohort_retention_heatmap.png", dpi=120)
plt.close()

fig, ax = plt.subplots(figsize=(10, 6))
for c in cohorts:
    ax.plot(ret.columns, ret.loc[c], marker="o", ms=3, label=c)
ax.set_title("Retention curves by signup cohort")
ax.set_xlabel("Months since signup"); ax.set_ylabel("Retention")
ax.legend(ncol=4, fontsize=8); ax.set_ylim(0, 1.02)
plt.tight_layout(); plt.savefig("../images/retention_curves.png", dpi=120)
plt.close()
log("\n=== Cohort retention (month-3 snapshot) ===")
m3 = ret[3].dropna()
log(f"Average month-3 retention across observable cohorts: {m3.mean():.1%}")
log(f"Best cohort: {m3.idxmax()} ({m3.max():.1%}) | Worst: {m3.idxmin()} ({m3.min():.1%})")

# ========================================== 4. Churn by plan and segment ===
def prop_ci(p, n, z=1.96):
    se = np.sqrt(p * (1 - p) / n)
    return p - z * se, p + z * se

def rate_table(col):
    g = df.groupby(col)["churned"].agg(["mean", "count"])
    g["lo"], g["hi"] = zip(*[prop_ci(p, n) for p, n in
                             zip(g["mean"], g["count"])])
    return g

plan_t = rate_table("plan").reindex(["Basic", "Pro", "Enterprise"])
seg_t = rate_table("segment").reindex(["Startup", "SMB", "Mid-market"])

fig, axes = plt.subplots(1, 2, figsize=(12, 5), sharey=True)
for ax, t, title in [(axes[0], plan_t, "Churn rate by plan"),
                     (axes[1], seg_t, "Churn rate by segment")]:
    x = np.arange(len(t))
    ax.bar(x, t["mean"], yerr=[t["mean"] - t["lo"], t["hi"] - t["mean"]],
           capsize=5, color=["#c0392b", "#e67e22", "#27ae60"][:len(t)])
    ax.set_xticks(x); ax.set_xticklabels(t.index)
    ax.set_title(title); ax.set_ylabel("Churn rate")
    for i, v in enumerate(t["mean"]):
        ax.text(i, v + 0.015, f"{v:.1%}", ha="center", fontsize=10)
    ax.set_ylim(0, t["hi"].max() * 1.25)
plt.suptitle("Churn rates with 95% confidence intervals")
plt.tight_layout(); plt.savefig("../images/churn_by_plan_segment.png", dpi=120)
plt.close()

log("\n=== Churn by plan (95% CI) ===")
for i, r in plan_t.iterrows():
    log(f"{i}: {r['mean']:.1%}  (CI {r['lo']:.1%} - {r['hi']:.1%}, n={r['count']})")
log("\n=== Churn by segment (95% CI) ===")
for i, r in seg_t.iterrows():
    log(f"{i}: {r['mean']:.1%}  (CI {r['lo']:.1%} - {r['hi']:.1%}, n={r['count']})")
worst_seg = seg_t["mean"].idxmax()
log(f"\nWorst segment: {worst_seg} at {seg_t.loc[worst_seg, 'mean']:.1%}")

# ======================================================= 5. Churn drivers ===
ch, re = df[df["churned"] == 1], df[df["churned"] == 0]
drivers = {
    "avg tenure (months)": (ch["tenure_months"].mean(), re["tenure_months"].mean()),
    "avg tickets / 90d": (ch["support_tickets_last_90d"].mean(),
                          re["support_tickets_last_90d"].mean()),
    "avg days since login": (ch["days_since_last_login"].mean(),
                             re["days_since_last_login"].mean()),
}
fig, axes = plt.subplots(1, 3, figsize=(13, 4.5))
for ax, (name, (cv, rv)) in zip(axes, drivers.items()):
    ax.bar(["churned", "retained"], [cv, rv], color=["#c0392b", "#27ae60"])
    ax.set_title(name)
    for i, v in enumerate([cv, rv]):
        ax.text(i, v * 1.02, f"{v:.1f}", ha="center", fontsize=11)
    ax.set_ylim(0, max(cv, rv) * 1.3)
plt.suptitle("Churn drivers: churned vs retained customers")
plt.tight_layout(); plt.savefig("../images/churn_drivers.png", dpi=120)
plt.close()

log("\n=== Churn drivers (churned vs retained) ===")
for name, (cv, rv) in drivers.items():
    log(f"{name}: churned {cv:.1f} vs retained {rv:.1f}")
log(f"High-ticket (>=4) churn rate: {df[df['is_high_ticket']==1]['churned'].mean():.1%} "
    f"vs low-ticket: {df[df['is_high_ticket']==0]['churned'].mean():.1%}")
log("\nChurn by recency bucket:")
log(df.groupby("recency_bucket", observed=True)["churned"].mean().mul(100).round(1).to_string())

# ============================================================== 6. LTV:CAC ==
ltv = df.groupby("segment").agg(
    avg_rev=("monthly_revenue", "mean"), avg_tenure=("tenure_months", "mean"))
ltv["LTV"] = ltv["avg_rev"] * ltv["avg_tenure"]
ltv["CAC_assumed"] = ltv.index.map(ASSUMED_CAC)
ltv["LTV:CAC"] = ltv["LTV"] / ltv["CAC_assumed"]
ltv = ltv.reindex(["Startup", "SMB", "Mid-market"])

fig, ax = plt.subplots(figsize=(9, 5))
x = np.arange(len(ltv)); w = 0.35
ax.bar(x - w/2, ltv["LTV"], w, label="LTV (₹)")
ax.bar(x + w/2, ltv["CAC_assumed"], w, label="CAC — ASSUMED (₹)")
for i, r in enumerate(ltv["LTV:CAC"]):
    ax.text(i, max(ltv.loc[ltv.index[i], "LTV"], ltv.loc[ltv.index[i], "CAC_assumed"]) * 1.03,
            f"{r:.1f}x", ha="center", fontsize=11, fontweight="bold")
ax.set_xticks(x); ax.set_xticklabels(ltv.index)
ax.set_title("LTV vs (assumed) CAC by segment")
ax.legend(); ax.set_ylabel("₹")
plt.tight_layout(); plt.savefig("../images/ltv_vs_cac.png", dpi=120)
plt.close()

log("\n=== LTV by segment (avg monthly revenue x avg tenure) ===")
for i, r in ltv.iterrows():
    log(f"{i}: LTV ₹{r['LTV']:,.0f} | CAC (ASSUMED) ₹{r['CAC_assumed']:,.0f} "
        f"| LTV:CAC = {r['LTV:CAC']:.1f}x")

# ========================================================= 7. MoM churn ===
# NOTE: start at 2025-11 — in 2025-10 the active base is empty
# (no signups before the first cohort), which would fake a 0.0% rate.
months = pd.period_range("2025-11", "2026-08", freq="M")
mom = []
for m in months:
    start = m.to_timestamp()
    active_start = df[(df["signup_date"] < start) &
                      (df["churn_date"].isna() | (df["churn_date"] >= start))]
    churned_m = df[(df["churn_date"] >= start) &
                   (df["churn_date"] < (m + 1).to_timestamp())]
    mom.append(len(churned_m) / max(len(active_start), 1))
mom = pd.Series(mom, index=months.astype(str))

fig, ax = plt.subplots(figsize=(10, 5))
ax.plot(mom.index, mom.values * 100, marker="o", color="#c0392b")
ax.set_title("Month-over-month churn rate (churned / active base at month start)")
ax.set_ylabel("Churn rate %"); ax.tick_params(axis="x", rotation=45)
ax.grid(True, alpha=0.3)
plt.tight_layout(); plt.savefig("../images/mom_churn_trend.png", dpi=120)
plt.close()
log("\n=== MoM churn trend ===")
log(f"Range: {mom.min():.1%} - {mom.max():.1%} | Latest (2026-08): {mom.iloc[-1]:.1%}")

# ================================================== 8. Chi-square test ===
ct = pd.crosstab(df["segment"], df["churned"])
chi2, p, dof, _ = stats.chi2_contingency(ct)
log("\n=== Chi-square: segment vs churn ===")
log(f"chi2 = {chi2:.1f}, dof = {dof}, p-value = {p:.2e}")
if p < 0.05:
    log("INTERPRETATION: p < 0.05 — the churn differences between segments are "
        "statistically significant; they are very unlikely to be random noise. "
        "Segment is a real churn driver.")
else:
    log("INTERPRETATION: p >= 0.05 — no significant difference detected.")

log("\n=== Overall 95% CI ===")
lo, hi = prop_ci(overall, N)
log(f"Overall churn rate {overall:.1%} (95% CI {lo:.1%} - {hi:.1%})")

with open("../results_summary.txt", "w") as f:
    f.write("\n".join(out) + "\n")
log("\nSaved: images/*.png (6 charts) + results_summary.txt")
